/// بيانات "آية وحديث اليوم": محتوى يتغيّر يومياً (وليس كل 4 ساعات كالمحتوى
/// المتجدد الآخر) يعرض آية قرآنية مع تفسير مختصر موثّق، وحديثاً نبوياً صحيحاً
/// مع شرح مختصر لمعناه. رُوعي عدم تكرار الآيات/الأحاديث المستخدمة أصلاً في
/// أقسام أخرى من التطبيق (كآية الكرسي أو أحاديث الأربعين النووية).
class DailyAyah {
  final String text;
  final String reference;
  final String tafsir;
  final String tafsirSource;
  const DailyAyah({required this.text, required this.reference, required this.tafsir, required this.tafsirSource});
}

class DailyHadith {
  final String text;
  final String narrator;
  final String source;
  final String sharh;
  const DailyHadith({required this.text, required this.narrator, required this.source, required this.sharh});
}

/// اختيار آية اليوم: ثابت طوال اليوم نفسه (بعكس المحتوى المتجدد كل ٤ ساعات)
/// ويتغيّر تلقائياً في اليوم التالي، بالاعتماد على عدد الأيام منذ ١٩٧٠.
DailyAyah ayahOfTheDay(DateTime date) {
  final epochDay = DateTime(date.year, date.month, date.day).millisecondsSinceEpoch ~/ (1000 * 60 * 60 * 24);
  return dailyAyahList[epochDay % dailyAyahList.length];
}

/// اختيار حديث اليوم: بنفس منطق آية اليوم، مع إزاحة بسيطة (+٧) حتى لا يتطابق
/// دائماً ترتيب الآية والحديث المختارين لنفس اليوم عبر كل الأيام.
DailyHadith hadithOfTheDay(DateTime date) {
  final epochDay = DateTime(date.year, date.month, date.day).millisecondsSinceEpoch ~/ (1000 * 60 * 60 * 24);
  return dailyHadithList[(epochDay + 7) % dailyHadithList.length];
}

